"""Export strict JSON Schemas and TypeScript from the canonical Pydantic models.
Run with --check in CI to detect drift. No network access or extra generators.
"""
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "apps/local-service"))
from app.schemas.interpret import InterpretRequest, InterpretResponse, ModelProposal

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        return "{ " + "; ".join(f'{key}{"" if key in required else "?"}: {ts(value)}' for key, value in schema["properties"].items()) + " }"
    if kind == "array":
        return f'Array<{ts(schema["items"])}>'
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[kind]


def outputs():
    definitions = {}
    result = {}
    for name, model in (("request", InterpretRequest), ("response", InterpretResponse), ("model", ModelProposal)):
        schema = model.model_json_schema()
        definitions.update(schema.get("$defs", {}))
        definitions[model.__name__] = {key: value for key, value in schema.items() if key != "$defs"}
        if name != "model":
            # Pydantic emits draft 2020-12; these schemas use the compatible draft-07 subset.
            schema["$schema"] = "http://json-schema.org/draft-07/schema#"
            schema["$id"] = f"https://piko.local/schemas/interpret-{name}.schema.json"
            result[ROOT / f"contracts/interpret-{name}.schema.json"] = json.dumps(schema, indent=2) + "\n"
    result[ROOT / "apps/extension/src/features/interpretation/interpretation.generated.ts"] = (
        "// Generated by scripts/generate-interpret-contracts.py. Do not edit.\n" +
        "\n".join(f"export type {name} = {ts(value)}" for name, value in sorted(definitions.items())) +
        "\nexport type InterpretTarget = TextTarget | OptionTarget | CheckboxTarget\n")
    return result


if __name__ == "__main__":
    for path, content in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated contract differs: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
